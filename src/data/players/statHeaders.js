/** Abbreviate known stats; unfamiliar backend fields retain a readable label. */
export function shortStatLabel(value) {
  const key = String(value);
  const parts = key.split("-");
  if (parts.length > 1) return parts.map(shortStatLabel).join("/");
  const normalized = key
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "")
    .replace(/^(avg|average|total)(?=[a-z])/, "");
  return abbreviations[normalized] || statLabel(key);
}
